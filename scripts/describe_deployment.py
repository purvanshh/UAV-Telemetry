"""Generate / check docs/DEPLOYED_MODEL.md from the deployed artifacts.

The document is the single authoritative description of what is deployed
(features, scaler, input shape, window parameters, threshold). It is generated,
so it cannot drift from ``uav_model/``; ``--check`` (and a unit test) fail when it does.

    python scripts/describe_deployment.py --write
    python scripts/describe_deployment.py --check
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.artifact_loader import load_artifacts  # noqa: E402
from src.provenance import artifact_fingerprints, feature_provenance  # noqa: E402

DOC = ROOT / "docs" / "DEPLOYED_MODEL.md"


def render(model_dir=None) -> str:
    a = load_artifacts(model_dir)
    import importlib.util

    spec = importlib.util.spec_from_file_location("prep", a.model_dir / "preprocessing.py")
    prep = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(prep)
    cfg = prep.DEFAULT_ALIGN
    fp = artifact_fingerprints(a)
    tc = a.threshold_config
    fs = a.feature_schema
    rows = feature_provenance(a, list(cfg["features"]))
    L = []
    L.append("# Deployed model — authoritative description\n")
    L.append("_Generated by `scripts/describe_deployment.py` from `uav_model/`. "
             "Do not edit by hand; run `--write` after changing artifacts. "
             "Other documents must link here rather than restate these values._\n")
    L.append("Scope: **telemetry anomaly detection only**. A flag means the window's "
             "reconstruction error exceeded the threshold; it is not a fault diagnosis.\n")
    L.append("## Model\n")
    L.append(f"- Architecture: `{a.model_config.get('architecture', 'LSTMAE')}` "
             f"(hidden {a.hidden_dim}, latent {a.latent_dim}, layers {a.num_layers})")
    L.append(f"- Variant: `{a.variant}`")
    L.append(f"- Input shape: `(batch, {a.win_samples}, {len(a.features)})` — "
             f"{a.win_samples} samples × {len(a.features)} features")
    L.append(f"- Score: mean squared error between input and reconstruction over all "
             f"{a.win_samples}×{len(a.features)} standardized values")
    L.append(f"- Checkpoint: `uav_model/lstm_autoencoder.pth` — sha256 `{fp['checkpoint']}`\n")
    L.append("## Preprocessing\n")
    L.append(f"- Alignment grid: {cfg['target_hz']:g} Hz, gap-aware linear interpolation; "
             f"values are not interpolated across source gaps > {cfg['max_gap_s']:g} s")
    L.append(f"- Session break: source gap > {cfg['session_gap_s']:g} s (windows never cross sessions)")
    L.append(f"- Windows: {a.win_samples} samples ({a.win_samples / cfg['target_hz']:g} s), "
             f"stride {a.stride_samples} samples ({a.stride_samples / cfg['target_hz']:g} s); "
             "a window with any non-finite deployed feature is discarded and counted")
    L.append("- Timestamps: `TimeUS` = microseconds (explicit); numeric `Timestamp` = microseconds "
             "by schema default (rate-checked); other units/datetime strings are rejected. "
             "Event times are the source log clock in seconds (see `src/timebase.py`)")
    L.append(f"- `preprocessing.py` sha256 `{fp['preprocessing_py']}`\n")
    L.append("## Features\n")
    L.append("| # | feature | stream | source field(s) | unit* | kind | scaler mean | scaler std |")
    L.append("|--:|---|---|---|---|---|--:|--:|")
    for r in rows:
        if r["used_by_model"]:
            L.append(f"| {r['model_input_index']} | `{r['feature']}` | {r['stream']} | "
                     f"{', '.join(r['source_fields'])} | {r['unit']} | {r['kind']} | "
                     f"{r['scaler_mean']:.6g} | {r['scaler_std']:.6g} |")
    L.append("\n\\*Units are those declared by `feature_schema.json`; they are not verified from uploaded logs.\n")
    excl = [r["feature"] for r in rows if not r["used_by_model"]]
    L.append(f"Computed by preprocessing but **not** scored by the model: {', '.join(f'`{e}`' for e in excl)}.\n")
    L.append("## Scaler\n")
    L.append("- Per-feature z-score `(x - mean) / std`; `std < 1e-12` is replaced by 1.0")
    L.append(f"- Fit on {len(a.scaler.get('fit_on_flights') or [])} training flights "
             f"(`scaler.json` `fit_on_flights`; equals `feature_schema.json` `split.train`: "
             f"{set(a.scaler.get('fit_on_flights') or []) == set(fs.get('split', {}).get('train', []))})")
    L.append(f"- `scaler.json` sha256 `{fp['scaler']}`\n")
    L.append("## Threshold\n")
    L.append(f"- Value: `{a.threshold!r}` (`threshold_config.json` key `lstm_ae`)")
    L.append(f"- Recorded provenance: quantile `{tc.get('quantile_used')}`, "
             f"calibrated on: \"{tc.get('calibrated_on')}\"")
    L.append("- Flag rule: `anomaly_score > threshold` (strict; equality is not a flag)")
    L.append("- **Verification status:** the recorded quantile and dataset are *claims* in a JSON "
             "file. The calibration script, validation scores and source flights are not in this "
             "repository, so the value has not been reproduced. See "
             "`outputs/evaluation/artifact_audit.json` (`python scripts/audit_artifacts.py`).")
    L.append(f"- `threshold_config.json` sha256 `{fp['threshold_config']}`\n")
    L.append("## Historical split (as recorded, unverified)\n")
    sp = fs.get("split", {})
    L.append(f"`feature_schema.json` lists {len(sp.get('train', []))} train / {len(sp.get('val', []))} val / "
             f"{len(sp.get('test', []))} test flight ids. The underlying flights are not in the repository, "
             "so leakage between these lists cannot be re-verified here.\n")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.write:
        DOC.parent.mkdir(parents=True, exist_ok=True)
        DOC.write_text(text)
        print(f"wrote {DOC}")
        return 0
    if not DOC.is_file() or DOC.read_text() != text:
        print("docs/DEPLOYED_MODEL.md is stale; run scripts/describe_deployment.py --write")
        return 1
    print("docs/DEPLOYED_MODEL.md is up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
